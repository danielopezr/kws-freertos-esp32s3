"""Generate the C constant tables for the firmware MFCC front end.

The firmware never recomputes window, filterbank, DCT or FFT twiddles: it uses
the exact float32 values produced here from kws/features.py, so the C and the
Python front ends cannot drift apart.

    python export_mfcc_tables.py            # writes ../firmware/components/kws_mfcc/kws_mfcc_tables.h
    python export_mfcc_tables.py --check    # exit 1 if the committed header is stale
"""

import argparse
import sys
from pathlib import Path

import numpy as np

from kws import features as F

OUT = Path(__file__).resolve().parents[1] / "firmware" / "components" / "kws_mfcc" / "kws_mfcc_tables.h"


def f32(v):
    """Shortest text that round-trips to the same float32."""
    return f"{np.float32(v)!r}".replace("np.float32(", "").rstrip(")") + "f"


def array(name, values, per_line=8, ctype="float"):
    vals = [f32(v) if ctype == "float" else str(int(v)) for v in values]
    lines = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n"


def render():
    window = F.hann_window()
    fb = F.mel_filterbank()
    dct = F.dct_matrix()

    # Sparse mel filterbank: each filter is a contiguous run of non-zero bins
    starts, lengths, offsets, weights = [], [], [], []
    for row in fb:
        nz = np.nonzero(row)[0]
        lo, hi = int(nz[0]), int(nz[-1])
        starts.append(lo)
        lengths.append(hi - lo + 1)
        offsets.append(len(weights))
        weights.extend(row[lo:hi + 1].tolist())

    k = np.arange(F.N_FFT // 2, dtype=np.float64)
    tw_cos = np.cos(2.0 * np.pi * k / F.N_FFT)
    tw_sin = np.sin(2.0 * np.pi * k / F.N_FFT)

    out = [
        "/* Generated by training/export_mfcc_tables.py from training/kws/features.py. Do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define KWS_MFCC_TABLES_SAMPLE_RATE {F.SAMPLE_RATE}",
        f"#define KWS_MFCC_TABLES_FRAME_LEN {F.FRAME_LEN}",
        f"#define KWS_MFCC_TABLES_N_FFT {F.N_FFT}",
        f"#define KWS_MFCC_TABLES_N_MELS {F.N_MELS}",
        f"#define KWS_MFCC_TABLES_N_MFCC {F.N_MFCC}",
        f"#define KWS_MFCC_TABLES_LOG_EPS {f32(F.LOG_EPS)}",
        f"#define KWS_MFCC_TABLES_N_WEIGHTS {len(weights)}",
        "",
        "/* Periodic Hann window */",
        array("kws_window", window),
        "/* cos / sin of 2*pi*k/N_FFT, k = 0 .. N_FFT/2 - 1 */",
        array("kws_tw_cos", tw_cos),
        array("kws_tw_sin", tw_sin),
        "/* Mel filter m covers bins [start, start + len) with weights kws_mel_w[offset ...] */",
        array("kws_mel_start", starts, 16, "uint16_t"),
        array("kws_mel_len", lengths, 16, "uint16_t"),
        array("kws_mel_offset", offsets, 16, "uint16_t"),
        array("kws_mel_w", weights),
        "/* Orthonormal DCT-II, row-major [N_MFCC][N_MELS] */",
        array("kws_dct", dct.reshape(-1)),
    ]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only verify that the header is up to date")
    args = ap.parse_args()
    text = render()
    if args.check:
        ok = OUT.exists() and OUT.read_text() == text
        print("up to date" if ok else f"STALE: regenerate {OUT}")
        sys.exit(0 if ok else 1)
    OUT.write_text(text, newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
